/*
 * Root layout — wraps every page on the site.
 *
 * `next/font/google` downloads the fonts at build time and injects them as
 * CSS variables, so there is no layout shift and no Google Fonts request
 * at runtime (better privacy and performance).
 *
 * Clay Playful branch: Fredoka (round display headings) + Nunito (soft body).
 * Both are variable fonts — no weight array needed.
 */
