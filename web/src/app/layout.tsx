/* LayoutProps is generated by Next.js from the route structure */
/*
 * Theme bootstrap — runs BEFORE first paint so the correct clay paper is
 * applied with no flash of the wrong theme (FOUC), and before hydration.
 * Priority: saved choice (localStorage["theme"]) → OS preference.
 */
const THEME_BOOTSTRAP = `(function(){try{var t=localStorage.getItem("theme");var d=t?t==="dark":window.matchMedia("(prefers-color-scheme: dark)").matches;if(d)document.documentElement.classList.add("dark");}catch(e){}})();`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${fredoka.variable} ${nunito.variable}`}
      suppressHydrationWarning
    >
      {/* suppressHydrationWarning: browser extensions (e.g. Grammarly) mutate
          this element's attributes before hydration; our theme bootstrap may
          also adjust the html class pre-paint. Only silences for this element. */}
      <body suppressHydrationWarning>
        <script dangerouslySetInnerHTML={{ __html: THEME_BOOTSTRAP }} />
        {/* Scroll furniture — reading progress + back-to-top */}
        <ProgressRule />
        <BackToTop />
        {children}
      </body>
    </html>
  );
}
