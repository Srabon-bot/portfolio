/* Fredoka — variable display face for h1–h3 and wordmarks */
const fredoka = Fredoka({
  subsets: ["latin"],
  variable: "--font-fredoka",
  display: "swap",
});

/* Nunito — soft rounded sans for body text */
const nunito = Nunito({
  subsets: ["latin"],
  variable: "--font-nunito",
  display: "swap",
});

