/* LayoutProps is generated by Next.js from the route structure */
/*
 * Theme bootstrap — runs BEFORE first paint so the correct paper is
 * applied with no flash of the wrong theme (FOUC), and before hydration.
 * Priority: saved choice (localStorage["theme"]) → OS preference.
 */
const THEME_BOOTSTRAP = `(function(){try{var t=localStorage.getItem("theme");var d=t?t==="dark":window.matchMedia("(prefers-color-scheme: dark)").matches;if(d)document.documentElement.classList.add("dark");}catch(e){}})();`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${inter.variable} ${jetbrainsMono.variable} ${fraunces.variable}`}
      suppressHydrationWarning
    >
      <body>
        <script dangerouslySetInnerHTML={{ __html: THEME_BOOTSTRAP }} />
        {/* Editorial scroll furniture — gold reading progress + back-to-top */}
        <ProgressRule />
        <BackToTop />
        {children}
      </body>
    </html>
  );
}
